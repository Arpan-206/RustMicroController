const TOP: u8 = 1 << 0;
const TL: u8 = 1 << 1;
const TR: u8 = 1 << 2;
const MID: u8 = 1 << 3;
const BL: u8 = 1 << 4;
const BR: u8 = 1 << 5;
const BOT: u8 = 1 << 6;

const SEG: [u8; 10] = [
    TOP | TL | TR | BL | BR | BOT,
    TR | BR,
    TOP | TR | MID | BL | BOT,
    TOP | TR | MID | BR | BOT,
    TL | TR | MID | BR,
    TOP | TL | MID | BR | BOT,
    TOP | TL | MID | BL | BR | BOT,
    TOP | TR | BR,
    TOP | TL | TR | MID | BL | BR | BOT,
    TOP | TL | TR | MID | BR | BOT,
];

const W: u16 = 16;
const H: u16 = 24;
const T: u16 = 3;

pub fn draw_char(x: u16, y: u16, ch: u8, colour: u8, scale: u16) {
    if !(32u8..=126u8).contains(&ch) || scale == 0 {
        return;
    }

    let glyph = &FONT[(ch - 32) as usize];
    let c = Colour(colour);

    for row in 0u16..7u16 {
        let mut span_start: Option<u16> = None;
        for col in 0u16..6u16 {
            let lit = col < 5 && ((glyph[col as usize] >> row) & 1) != 0;
            if lit {
                if span_start.is_none() {
                    span_start = Some(col);
                }
            } else if let Some(start_col) = span_start {
                fill_scaled_span(x, y, row, start_col, col - 1, c, scale);
                span_start = None;
            }
        }
        if let Some(start_col) = span_start {
            fill_scaled_span(x, y, row, start_col, 4, c, scale);
        }
    }
}

pub fn draw_str(x: u16, y: u16, s: &[u8], colour: u8, scale: u16) {
    let mut cursor = x;
    for &ch in s {
        draw_char(cursor, y, ch, colour, scale);
        cursor = cursor.saturating_add(char_width(scale));
    }
}

pub const fn char_width(scale: u16) -> u16 {
    6 * scale
}

pub const fn char_height(scale: u16) -> u16 {
    7 * scale
}

fn fill_scaled_span(
    x: u16,
    y: u16,
    row: u16,
    start_col: u16,
    end_col: u16,
    colour: Colour,
    scale: u16,
) {
    let x0 = x + start_col * scale;
    let y0 = y + row * scale;
    let x1 = x + (end_col + 1) * scale - 1;
    let y1 = y + (row + 1) * scale - 1;
    fill_rect(x0, y0, x1, y1, colour);
}

// 7-segment digit display
// Segments:  0=top  1=top-left  2=top-right  3=mid  4=bot-left  5=bot-right  6=bottom
//
//   _
//  | |
//   -
//  | |
//   -

pub fn draw_digit(x: u16, y: u16, digit: u8, colour: u8) {
    let d = digit as usize;
    if d > 9 {
        return;
    }

    let s = SEG[d];
    let c = Colour(colour);

    if s & (1 << 0) != 0 {
        fill_rect(x, y, x + W, y + T, c);
    }
    if s & (1 << 1) != 0 {
        fill_rect(x, y, x + T, y + H / 2, c);
    }
    if s & (1 << 2) != 0 {
        fill_rect(x + W - T, y, x + W, y + H / 2, c);
    }
    if s & (1 << 3) != 0 {
        fill_rect(x, y + H / 2 - T / 2, x + W, y + H / 2 + T / 2, c);
    }
    if s & (1 << 4) != 0 {
        fill_rect(x, y + H / 2, x + T, y + H, c);
    }
    if s & (1 << 5) != 0 {
        fill_rect(x + W - T, y + H / 2, x + W, y + H, c);
    }
    if s & (1 << 6) != 0 {
        fill_rect(x, y + H - T, x + W, y + H, c);
    }
}

pub fn erase_digit(x: u16, y: u16) {
    fill_rect(x, y, x + W, y + H, Colour(crate::pong::BG));
}
