use crate::display::fill_rect;
use crate::display::Colour;

// 8x8 font for ASCII 32..126.
// Uppercase A..Z use the provided glyphs.
// Lowercase letters map to uppercase so title-case text still renders.
// Each byte is one row, with bit 7 as the leftmost pixel.

fn glyph(ch: u8) -> [u8; 8] {
    let ch = if ch >= b'a' && ch <= b'z' {
        ch - 32
    } else {
        ch
    };

    match ch {
        b' ' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
        b'!' => [0x18, 0x3C, 0x3C, 0x18, 0x18, 0x00, 0x18, 0x00],
        b'.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x18, 0x18, 0x00],
        b'0' => [0x3E, 0x63, 0x73, 0x7B, 0x6F, 0x67, 0x3E, 0x00],
        b'1' => [0x0C, 0x0E, 0x0C, 0x0C, 0x0C, 0x0C, 0x3F, 0x00],
        b'2' => [0x1E, 0x33, 0x30, 0x1C, 0x06, 0x33, 0x3F, 0x00],
        b'3' => [0x1E, 0x33, 0x30, 0x1C, 0x30, 0x33, 0x1E, 0x00],
        b'4' => [0x38, 0x3C, 0x36, 0x33, 0x7F, 0x30, 0x78, 0x00],
        b'5' => [0x3F, 0x03, 0x1F, 0x30, 0x30, 0x33, 0x1E, 0x00],
        b'6' => [0x1C, 0x06, 0x03, 0x1F, 0x33, 0x33, 0x1E, 0x00],
        b'7' => [0x3F, 0x33, 0x30, 0x18, 0x0C, 0x0C, 0x0C, 0x00],
        b'8' => [0x1E, 0x33, 0x33, 0x1E, 0x33, 0x33, 0x1E, 0x00],
        b'9' => [0x1E, 0x33, 0x33, 0x3E, 0x30, 0x18, 0x0E, 0x00],
        b'A' => [0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00],
        b'B' => [0x3F, 0x66, 0x66, 0x3E, 0x66, 0x66, 0x3F, 0x00],
        b'C' => [0x3C, 0x66, 0x03, 0x03, 0x03, 0x66, 0x3C, 0x00],
        b'D' => [0x1F, 0x36, 0x66, 0x66, 0x66, 0x36, 0x1F, 0x00],
        b'E' => [0x7F, 0x46, 0x16, 0x1E, 0x16, 0x46, 0x7F, 0x00],
        b'F' => [0x7F, 0x46, 0x16, 0x1E, 0x16, 0x06, 0x0F, 0x00],
        b'G' => [0x3C, 0x66, 0x03, 0x03, 0x73, 0x66, 0x7C, 0x00],
        b'H' => [0x33, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x33, 0x00],
        b'I' => [0x1E, 0x0C, 0x0C, 0x0C, 0x0C, 0x0C, 0x1E, 0x00],
        b'J' => [0x78, 0x30, 0x30, 0x30, 0x33, 0x33, 0x1E, 0x00],
        b'K' => [0x67, 0x66, 0x36, 0x1E, 0x36, 0x66, 0x67, 0x00],
        b'L' => [0x0F, 0x06, 0x06, 0x06, 0x46, 0x66, 0x7F, 0x00],
        b'M' => [0x63, 0x77, 0x7F, 0x7F, 0x6B, 0x63, 0x63, 0x00],
        b'N' => [0x63, 0x67, 0x6F, 0x7B, 0x73, 0x63, 0x63, 0x00],
        b'O' => [0x1C, 0x36, 0x63, 0x63, 0x63, 0x36, 0x1C, 0x00],
        b'P' => [0x3F, 0x66, 0x66, 0x3E, 0x06, 0x06, 0x0F, 0x00],
        b'Q' => [0x1E, 0x33, 0x33, 0x33, 0x3B, 0x1E, 0x38, 0x00],
        b'R' => [0x3F, 0x66, 0x66, 0x3E, 0x36, 0x66, 0x67, 0x00],
        b'S' => [0x1E, 0x33, 0x07, 0x0E, 0x38, 0x33, 0x1E, 0x00],
        b'T' => [0x3F, 0x2D, 0x0C, 0x0C, 0x0C, 0x0C, 0x1E, 0x00],
        b'U' => [0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x3F, 0x00],
        b'V' => [0x33, 0x33, 0x33, 0x33, 0x33, 0x1E, 0x0C, 0x00],
        b'W' => [0x63, 0x63, 0x63, 0x6B, 0x7F, 0x77, 0x63, 0x00],
        b'X' => [0x63, 0x63, 0x36, 0x1C, 0x1C, 0x36, 0x63, 0x00],
        b'Y' => [0x33, 0x33, 0x33, 0x1E, 0x0C, 0x0C, 0x1E, 0x00],
        b'Z' => [0x7F, 0x63, 0x31, 0x18, 0x4C, 0x66, 0x7F, 0x00],
        _ => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
    }
}

pub fn draw_char(x: u16, y: u16, ch: u8, colour: u8, scale: u16) {
    if !(32u8..=126u8).contains(&ch) || scale == 0 {
        return;
    }

    let glyph = glyph(ch);
    let c = Colour(colour);

    for row in 0u16..8u16 {
        let row_byte = glyph[row as usize];
        for col in 0u16..8u16 {
            let mask = 1u8 << (7 - col);
            if row_byte & mask != 0 {
                let x0 = x + col * scale;
                let y0 = y + row * scale;
                fill_rect(x0, y0, x0 + scale - 1, y0 + scale - 1, c);
            }
        }
    }
}

pub fn draw_str(x: u16, y: u16, s: &[u8], colour: u8, scale: u16) {
    let mut cursor = x;
    for &ch in s {
        draw_char(cursor, y, ch, colour, scale);
        cursor = cursor.saturating_add(char_width(scale));
    }
}

pub const fn char_width(scale: u16) -> u16 {
    8 * scale
}

pub const fn char_height(scale: u16) -> u16 {
    8 * scale
}

const W: u16 = 16;
const H: u16 = 24;
const T: u16 = 3;

const TOP: u8 = 1 << 0;
const TL: u8 = 1 << 1;
const TR: u8 = 1 << 2;
const MID: u8 = 1 << 3;
const BL: u8 = 1 << 4;
const BR: u8 = 1 << 5;
const BOT: u8 = 1 << 6;

const SEG: [u8; 10] = [
    TOP | TL | TR | BL | BR | BOT,
    TR | BR,
    TOP | TR | MID | BL | BOT,
    TOP | TR | MID | BR | BOT,
    TL | TR | MID | BR,
    TOP | TL | MID | BR | BOT,
    TOP | TL | MID | BL | BR | BOT,
    TOP | TR | BR,
    TOP | TL | TR | MID | BL | BR | BOT,
    TOP | TL | TR | MID | BR | BOT,
];

pub fn draw_digit(x: u16, y: u16, digit: u8, colour: u8) {
    let d = digit as usize;
    if d > 9 {
        return;
    }

    let s = SEG[d];
    let c = Colour(colour);

    if s & (1 << 0) != 0 {
        fill_rect(x, y, x + W, y + T, c);
    }
    if s & (1 << 1) != 0 {
        fill_rect(x, y, x + T, y + H / 2, c);
    }
    if s & (1 << 2) != 0 {
        fill_rect(x + W - T, y, x + W, y + H / 2, c);
    }
    if s & (1 << 3) != 0 {
        fill_rect(x, y + H / 2 - T / 2, x + W, y + H / 2 + T / 2, c);
    }
    if s & (1 << 4) != 0 {
        fill_rect(x, y + H / 2, x + T, y + H, c);
    }
    if s & (1 << 5) != 0 {
        fill_rect(x + W - T, y + H / 2, x + W, y + H, c);
    }
    if s & (1 << 6) != 0 {
        fill_rect(x, y + H - T, x + W, y + H, c);
    }
}

pub fn erase_digit(x: u16, y: u16) {
    fill_rect(x, y, x + W, y + H, Colour(crate::pong::BG));
}